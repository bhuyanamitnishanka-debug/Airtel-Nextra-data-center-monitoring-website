// Helper to calculate realistic Server Rack working flow telemetry correlated to IT Load (MW)
export const enrichPointWithServerRackFlow = (point: HistoricalDataPoint): HistoricalDataPoint => {
  const loadRatio = point.itLoadMw / 2.5; // baseline around 2.5 MW
  const clientRequestsPerSec = Math.round(155000 * loadRatio + (point.day % 5) * 2400);
  const dataServedGbps = Number((point.networkFiberGbps * 0.92).toFixed(1));
  const cpuProcessingPercent = Number(Math.min(94, 62 * loadRatio + (point.day % 4) * 1.8).toFixed(1));
  const ramMemoryPercent = Number(Math.min(96, 68 * loadRatio + (point.day % 3) * 1.4).toFixed(1));
  const storageIops = Math.round(52000 * loadRatio + (point.day % 6) * 1200);
  const storageThroughputMBs = Math.round(890 * loadRatio + (point.day % 5) * 35);
  const pduBranchAmps = Number((26.4 * (point.itLoadMw / 2.45)).toFixed(1));
  const airflowCfm = Math.round(2550 * loadRatio);
  const rackDeltaTempC = Number((11.5 + (point.itLoadPeakMw - 2.1) * 2.8).toFixed(1));

  return {
    ...point,
    clientRequestsPerSec,
    dataServedGbps,
    cpuProcessingPercent,
    ramMemoryPercent,
    storageIops,
    storageThroughputMBs,
    pduBranchAmps,
    airflowCfm,
    rackDeltaTempC,
  };
};

